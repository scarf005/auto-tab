export type TranslationKey = keyof typeof translations.en
// ko must define every key en does.
translations.ko satisfies Record<TranslationKey, string>

export function detectLanguage(): Language {
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language || ""]
  return languages.some((x) => String(x).toLowerCase().startsWith("ko")) ? "ko" : "en"
}

export function translate(
  language: Language,
  key: TranslationKey,
  vars: Record<string, string | number> = {},
): string {
  let value: string = translations[language]?.[key] ?? translations.en[key] ?? key
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement))
  }
  return value
}
